// Package i18n holds Kursor's UI translations (Ukrainian and English for
// now — see the project plan) and a small lookup helper. Kept as a plain
// in-memory dictionary rather than .po/.json files: the string set is
// still small enough that a single reviewable Go map is the simplest
// thing that works.
package i18n

// DefaultLang is used when no language cookie is set yet.
const DefaultLang = "uk"

// Supported reports whether code is a language Kursor has translations for.
func Supported(code string) bool {
	_, ok := dict["nav.dashboard"][code]
	return ok
}

// T looks up key for lang, falling back to English and then to the raw
// key itself so a missing translation is obvious rather than blank.
func T(lang, key string) string {
	entry, ok := dict[key]
	if !ok {
		return key
	}
	if v, ok := entry[lang]; ok {
		return v
	}
	if v, ok := entry["en"]; ok {
		return v
	}
	return key
}

